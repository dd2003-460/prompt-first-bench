    "1. cartesian（笛卡尔积）【默认】：子维度独立取值，联合空间 = 各维度取值组合，无交叉约束。\n"
    "例：某产品的「维度A、维度B、维度C」之间。\n"
    "2. quotient（商/约束）：判定的唯一条件是——父概念的定义本身就是子项的运算结果"
