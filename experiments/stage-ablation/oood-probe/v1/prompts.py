    "存在 trade-off——一个分量↑另一个分量↓时最终目标可能不变。"
    "例：性价比 = 性能 / 总成本；效率比 = 产出 / 投入。\n"
    "注意：大多数分解边是 cartesian。只有当父概念明确是\"A 与 B 的运算\"时才判 quotient，"
